#!/usr/bin/env node

// Fetches Bing's picture of the day and writes it to assets/css/wallpaper.css
// as custom properties.
//
// This runs in CI rather than in the browser on purpose: Bing's
// HPImageArchive endpoint sends no Access-Control-Allow-Origin header, so a
// fetch() from the page is blocked. Resolving the URL at build time also
// avoids depending on a third-party CORS proxy at runtime.

const fs = require('fs');
const path = require('path');

const API = 'https://www.bing.com/HPImageArchive.aspx?format=js&idx=0&n=1&mkt=en-US';
const OUT = path.join(__dirname, '..', 'assets', 'css', 'wallpaper.css');

// Escapes a value for use inside a double-quoted CSS string.
function cssString(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

async function main() {
  const response = await fetch(API, {
    headers: { 'User-Agent': 'Mozilla/5.0 (compatible; wallpaper-updater)' },
  });

  if (!response.ok) {
    throw new Error(`Bing returned HTTP ${response.status}`);
  }

  const image = (await response.json()).images?.[0];

  if (!image?.urlbase) {
    throw new Error('Bing response contained no image');
  }

  // urlbase omits the resolution suffix, so we pick it ourselves.
  const url = `https://www.bing.com${image.urlbase}_1920x1080.jpg`;
  const credit = image.copyright || '';

  const lines = [
    '/* Generated by scripts/bing-wallpaper.js. Do not edit by hand. */',
    ':root {',
    `\t--bing-wallpaper: url("${cssString(url)}");`,
  ];

  if (credit) {
    lines.push(`\t--bing-copyright: "${cssString(credit)}";`);
  }

  lines.push('}');

  const css = `${lines.join('\n')}\n`;

  fs.writeFileSync(OUT, css);
  console.log(`Wallpaper: ${url}`);
  console.log(`Credit:    ${credit}`);
}

main().catch((error) => {
  console.error(`Failed to update wallpaper: ${error.message}`);
  process.exit(1);
});
